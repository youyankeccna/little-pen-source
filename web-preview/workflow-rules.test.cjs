const assert=require('node:assert/strict');
const W=require('./workflow-rules.js'),C=require('./curriculum/data.js');
assert.deepEqual(W.gradeOptions('en').map(row=>row[0]),['3','4','5','6']);
for(const grade of [0,1,2])assert.equal(W.normalizeGrade(grade,'en'),3);
for(const grade of [3,4,5,6])assert.equal(W.normalizeGrade(grade,'en'),grade);
assert(W.gradeOptions('cn').some(row=>row[0]==='1'));assert(W.gradeOptions('math').some(row=>row[0]==='2'));
assert.equal(W.normalizeGrade(1,'cn'),1);assert.equal(W.normalizeGrade(2,'math'),2);
const l=C.getLesson('cn-1u-tiandiren'),context={grade:1,subject:'cn',term:'upper'};
assert.equal(W.matches(l,context,'pep'),true);
assert.equal(W.matches(l,{...context,grade:2},'pep'),false,'a grade change must not resume the old book');
assert.equal(W.matches(l,context,'different'),false,'a textbook change must not resume the old book');
assert.equal(W.matches(l,context,'pep','en'),false,'explicit subject navigation takes priority');
assert.equal(W.matches(null,context,'pep'),false);
const pack=l.packs[0],selection=C.getSelection(l.id,pack.kind,pack.items.slice(0,2).map(i=>i.id));
const url=W.editorUrl(selection);assert.ok(url.startsWith('#/hanzi?'));const params=new URLSearchParams(url.split('?')[1]);assert.equal(params.get('course'),l.id);assert.deepEqual(params.get('items').split(','),selection.itemIds);
assert.equal(W.editorUrl({...selection,itemIds:[]}),null,'an empty selection returns to choosing content');
const plans=[{id:'yesterday',mode:'daily',days:[{date:'2026-10-22'}]},{id:'today',mode:'daily',days:[{date:'2026-10-23',completed:true}]},{id:'week',mode:'weekly',days:[{date:'2026-10-22'},{date:'2026-10-26'}]}];
assert.equal(W.activePlan(plans,'daily','2026-10-23').id,'today','completed work is still available without rebuilding');
assert.equal(W.activePlan(plans,'weekly','2026-10-23').id,'week');
assert.equal(W.activePlan(plans,'weekly','2026-10-27'),undefined,'an expired week opens a new arrangement');
console.log('PASS: curriculum-aware resume, exact selections, empty selection and dated plan reuse');
